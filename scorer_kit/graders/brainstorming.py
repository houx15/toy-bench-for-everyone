"""Brainstorming: taste-heavy. Novelty is distance from a baseline idea pool, diversity is
the number of distinct clusters, usefulness is a 1-3 judgement calibrated against the user's
own ratings.

The baseline pool is the task's static ``baseline_ideas`` plus, leave-one-out, the ideas the
*other* models in the run produced for the same task. A model is never compared against a
pool containing its own ideas.
"""

from __future__ import annotations

import json
import random
import re
from typing import Any

from pydantic import BaseModel, Field

from scorer_kit.graders import similarity
from scorer_kit.graders.base import (
    CalibrationUnit, GradeContext, Grader, Grading, JudgeParseError, fill, format_anchors,
    parse_judge_json,
)
from scorer_kit.schemas import Job, Message, Recipe, Task

LIST_ITEM = re.compile(r"^\s*(?:\d+[.)]|[-*•])\s+(\S.*?)\s*$")


class BrainstormGold(BaseModel):
    goal: str = Field(description="What a useful idea achieves for the user, in their words.")
    target_count: int = Field(default=10, ge=1)
    baseline_ideas: list[str] = Field(
        default_factory=list, description="Obvious ideas, e.g. generated by models not under test."
    )


def parse_ideas(text: str) -> list[str]:
    items = [m.group(1) for line in text.splitlines() if (m := LIST_ITEM.match(line))]
    if items:
        return items
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]


class BrainstormGrader(Grader):
    name = "brainstorming"
    gold_model = BrainstormGold

    def task_prompt_suffix(self, task: Task, recipe: Recipe) -> str:
        gold = BrainstormGold.model_validate(task.gold)
        return f"Give {gold.target_count} ideas."

    def judge_messages(self, task, recipe, output, attachments):
        gold = BrainstormGold.model_validate(task.gold)
        prompt = fill(
            recipe.judge.prompt,
            request=task.input.prompt,
            goal=gold.goal,
            output=output,
            usefulness_anchors=format_anchors(recipe, "usefulness"),
        )
        return [Message(role="system", content=recipe.judge.system),
                Message(role="user", content=prompt)]

    def grade(self, task, recipe, output, judge_reply, ctx: GradeContext) -> Grading:
        gold = BrainstormGold.model_validate(task.gold)
        p = recipe.params
        ideas = parse_ideas(output)
        criteria: dict[str, float] = {}
        flags: list[str] = []
        details: dict[str, Any] = {"idea_count": len(ideas)}

        if not ideas:
            return Grading({"count": 0.0}, details, ["no-ideas-parsed"])
        criteria["count"] = min(1.0, len(ideas) / gold.target_count)

        pool = list(gold.baseline_ideas)
        for peer in ctx.peer_outputs:
            pool += parse_ideas(peer)
        details["baseline_pool_size"] = len(pool)
        if pool:
            nov = similarity.novelty(ideas, pool)
            details["novelty_per_idea"] = [round(n, 3) for n in nov]
            criteria["novelty"] = sum(nov) / len(nov)
        else:
            flags.append("no-baseline-pool")

        clusters = similarity.leader_clusters(ideas, p.get("cluster_threshold", 0.5))
        details["clusters"] = len(clusters)
        criteria["diversity"] = len(clusters) / max(len(ideas), gold.target_count)

        if judge_reply is None:
            flags.append("no-judge")
            return Grading(criteria, details, flags)
        try:
            j = parse_judge_json(judge_reply)
        except JudgeParseError as e:
            details["judge_error"] = str(e)
            return Grading(criteria, details, flags + ["judge-unparseable"])
        scale = recipe.criterion("usefulness").scale
        try:
            u = float(j.get("usefulness"))
        except (TypeError, ValueError):
            flags.append("judge-missing-usefulness")
        else:
            details["usefulness"] = u
            details["best_idea"] = j.get("best_idea")
            criteria["usefulness"] = scale.normalize(u)
        return Grading(criteria, details, flags)

    def calibration_units(self, recipe, details):
        if "usefulness" not in details:
            return []
        s = recipe.criterion("usefulness").scale
        return [CalibrationUnit(
            "usefulness", "overall", "ordinal", details["usefulness"],
            "How useful is this idea list for your goal?",
            list(range(int(s.min), int(s.max) + 1)))]

    # -- mocks

    _WORDS = ["podcast", "workshop", "newsletter", "toolkit", "dataset", "game", "survey",
              "map", "challenge", "library", "tutorial", "bot", "zine", "audit", "festival"]
    _ANGLES = ["for beginners", "with local partners", "as a weekly ritual", "using open data",
               "in reverse", "for skeptics", "as a public log", "in 5 minutes a day"]

    def mock_output(self, job: Job, skill: float, rng: random.Random) -> str:
        gold = BrainstormGold.model_validate(job.meta["gold"])
        n_words = max(2, round(len(self._WORDS) * skill))
        words = rng.sample(self._WORDS, n_words)
        ideas = [f"{rng.choice(words).title()} {rng.choice(self._ANGLES)}"
                 for _ in range(gold.target_count)]
        return "\n".join(f"{i}. {idea}" for i, idea in enumerate(ideas, 1))

    def mock_judgement(self, job: Job, rng: random.Random) -> str:
        return json.dumps({"usefulness": rng.choice([1, 2, 2, 3]), "best_idea": 1,
                           "reason": "mock judgement"})
